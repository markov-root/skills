"""Optional POSIX launchers with explicit declarations and ownership checks."""

import hashlib
import json
import os
from pathlib import Path
import shlex
import shutil
import tempfile

from .artifacts import NAME, Refusal, identity


def fingerprint(path):
    if path.is_symlink():
        return {"kind": "symlink", "target": os.readlink(path)}
    if not path.exists():
        return None
    if not path.is_file():
        return {"kind": "other"}
    return {
        "kind": "file",
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        "mode": path.stat().st_mode & 0o777,
    }


def declarations(root):
    root = Path(root).resolve(strict=True)
    meta = identity(root)
    path = root / "assets/cli.json"
    if not path.exists():
        return meta["name"], []
    data = json.loads(path.read_text())
    if data.get("schema_version") != 1 or not isinstance(data.get("commands"), dict):
        raise Refusal("expected assets/cli.json schema_version 1 and commands mapping")
    commands = []
    for name, spec in sorted(data["commands"].items()):
        if not NAME.fullmatch(name) or len(name) > 64 or not isinstance(spec, dict):
            raise Refusal("invalid declared command")
        if set(spec) - {"runner", "path", "args"}:
            raise Refusal(f"unknown command fields: {name}")
        relative = Path(spec["path"])
        if (
            relative.is_absolute()
            or ".." in relative.parts
            or not relative.parts
            or relative.parts[0] != "scripts"
        ):
            raise Refusal("CLI targets must be relative paths inside scripts")
        target = (root / relative).resolve(strict=True)
        if not target.is_relative_to(root) or not target.is_file():
            raise Refusal("CLI target escapes the installed artifact or is not a file")
        runner = spec["runner"]
        prefixes = {
            "python3": ["python3"],
            "bash": ["bash"],
            "uv": ["uv", "run", "--script"],
            "exec": [],
        }
        if runner not in prefixes:
            raise Refusal("runner must be python3, bash, uv, or exec")
        if runner == "exec" and not os.access(target, os.X_OK):
            raise Refusal(f"target is not executable: {name}")
        extra = spec.get("args", [])
        if not isinstance(extra, list) or not all(
            isinstance(a, str) and "\x00" not in a for a in extra
        ):
            raise Refusal("command args must be strings")
        argv = prefixes[runner] + [str(target)] + extra
        missing = None if runner == "exec" or shutil.which(argv[0]) else argv[0]
        content = (
            "#!/bin/sh\n# generated by skill-manager; ownership is recorded separately\nexec "
            + shlex.join(argv)
            + ' "$@"\n'
        )
        commands.append(
            {
                "command": name,
                "skill": meta["name"],
                "root": str(root),
                "target": str(target),
                "argv": argv,
                "content": content,
                "missing_prerequisite": missing,
            }
        )
    return meta["name"], commands


def cli_plan(env, root, bin_dir, adopt=False, remove=False):
    name, commands = declarations(root)
    state = env.state()
    bin_dir = Path(bin_dir).expanduser().resolve()
    expected = {str(bin_dir / c["command"]): c for c in commands}
    # Stale declared names remain in the plan so a rename cleans only owned entries.
    paths = set(expected) | {
        p
        for p, v in state["launchers"].items()
        if v["skill"] == name and Path(p).parent == bin_dir
    }
    items = []
    for p in sorted(paths):
        target = Path(p)
        current = fingerprint(target)
        previous = state["launchers"].get(p)
        command = expected.get(p)
        owned = (
            previous is not None
            and previous["skill"] == name
            and previous["fingerprint"] == current
        )
        legacy = bool(
            adopt
            and command
            and current == {"kind": "symlink", "target": command["target"]}
        )
        # A bounded migration adapter for the old portfolio's exact uv wrapper.
        # No shell parsing/evaluation and no adoption of edited or arbitrary files.
        if adopt and command and current and current.get("kind") == "file":
            old = (
                "#!/usr/bin/env bash\n"
                "# generated by Skills/scripts/expose-clis.sh — do not edit\n"
                f'exec uv run --script "{command["target"]}" "$@"\n'
            )
            legacy = (
                command["argv"] == ["uv", "run", "--script", command["target"]]
                and bool(current["mode"] & 0o111)
                and current["sha256"] == hashlib.sha256(old.encode()).hexdigest()
            )
        action = "remove" if remove or command is None else "write"
        conflict = current is not None and not owned and not legacy
        shadow = shutil.which(target.name)
        if shadow and Path(shadow).absolute() != target.absolute():
            conflict = True
        if action == "write" and command["missing_prerequisite"]:
            conflict = True
        items.append(
            {
                "path": p,
                "action": action,
                "before": current,
                "owned": owned,
                "legacy_adoption": legacy,
                "conflict": conflict,
                "shadow": shadow
                if shadow and Path(shadow).absolute() != target.absolute()
                else None,
                "declaration": command,
            }
        )
    return {
        "kind": "cli-plan",
        "skill": name,
        "root": str(Path(root).resolve()),
        "bin_dir": str(bin_dir),
        "adopt": adopt,
        "remove": remove,
        "items": items,
        "status": "conflict" if any(i["conflict"] for i in items) else "planned",
    }


def cli_apply(env, supplied):
    with env.lock():
        current = cli_plan(
            env,
            supplied["root"],
            supplied["bin_dir"],
            supplied["adopt"],
            supplied["remove"],
        )
        if current != supplied or current["status"] == "conflict":
            raise Refusal(
                "CLI plan is stale or has collisions, shadowing, modified owners, or missing prerequisites"
            )
        state = env.state()
        for item in current["items"]:
            target = Path(item["path"])
            if item["action"] == "remove":
                if item["before"] is not None:
                    target.unlink()
                state["launchers"].pop(str(target), None)
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                fd, temporary = tempfile.mkstemp(
                    prefix=".skill-manager-", dir=target.parent
                )
                try:
                    with os.fdopen(fd, "w") as stream:
                        stream.write(item["declaration"]["content"])
                        stream.flush()
                        os.fsync(stream.fileno())
                    os.chmod(temporary, 0o755)
                    os.replace(temporary, target)
                finally:
                    if os.path.exists(temporary):
                        os.unlink(temporary)
                state["launchers"][str(target)] = {
                    "skill": current["skill"],
                    "root": current["root"],
                    "fingerprint": fingerprint(target),
                }
            env.save(state)
        return {**current, "kind": "cli-receipt", "status": "applied"}


def health(env):
    result = []
    for path, item in env.state()["launchers"].items():
        try:
            _, commands = declarations(item["root"])
            command = next(
                (c for c in commands if c["command"] == Path(path).name), None
            )
            expected = (
                hashlib.sha256(command["content"].encode()).hexdigest()
                if command
                else None
            )
            actual = fingerprint(Path(path))
            selected = shutil.which(Path(path).name)
            ok = (
                actual == item["fingerprint"]
                and actual
                and actual.get("sha256") == expected
                and not command["missing_prerequisite"]
                and selected == path
            )
            result.append(
                {
                    "path": path,
                    "skill": item["skill"],
                    "status": "healthy" if ok else "broken",
                    "selected_on_path": selected,
                }
            )
        except (OSError, ValueError, KeyError) as exc:
            result.append(
                {
                    "path": path,
                    "skill": item["skill"],
                    "status": "broken",
                    "error": str(exc),
                }
            )
    return result
